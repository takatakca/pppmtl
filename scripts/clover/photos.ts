/**
 * Real menu photos, keyed by Clover item id: public/menu/clover/<cloverItemId>-1200.webp and -400.webp (4:3),
 * plus src/data/clover/photos.generated.ts (which items have one). The site falls back to its category photo.
 *
 *   npm run clover:photos -- <photos folder>
 *
 * The folder holds the owner's photos and a `_list.tsv` (file name, source, Clover item id, name, origin — tab
 * separated). It is kept outside this repository; only the optimised copies are committed.
 * Needs `sharp` (not a site dependency): `npm i --no-save sharp`, or SHARP_PATH=<folder of an installed sharp>.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

type Sharp = (input: string) => {
  resize: (
    w: number,
    h: number,
    o: { fit: "cover"; position: "centre" },
  ) => {
    webp: (o: { quality: number }) => { toFile: (path: string) => Promise<unknown> };
  };
};

async function loadSharp(): Promise<Sharp> {
  const fromPath = process.env["SHARP_PATH"];
  const mod = (await (fromPath
    ? import(pathToFileURL(join(fromPath, "lib", "index.js")).href)
    : import("sharp" as string))) as { default: Sharp };
  return mod.default;
}

const dir = process.argv[2];
if (!dir || !existsSync(join(dir, "_list.tsv"))) {
  console.error("Usage: npm run clover:photos -- <folder with the photos and _list.tsv>");
  process.exit(1);
}

const root = new URL("../../", import.meta.url);
const snapshot = JSON.parse(
  readFileSync(new URL("src/data/clover/inventory.snapshot.json", root), "utf8"),
) as {
  items: Array<{ id: string }>;
};
const sold = new Set(snapshot.items.map((i) => i.id));
const outDir = new URL("public/menu/clover/", root);
mkdirSync(outDir, { recursive: true });

const sharp = await loadSharp();
const done: string[] = [];
for (const line of readFileSync(join(dir, "_list.tsv"), "utf8").split(/\r?\n/)) {
  const [file, , id] = line.split("\t");
  if (!file || !id || !/^[A-Z0-9]{13}$/.test(id) || !sold.has(id) || done.includes(id)) continue;
  const input = join(dir, file);
  if (!existsSync(input)) continue;
  for (const [w, h, q] of [
    [1200, 900, 72],
    [400, 300, 70],
  ] as const) {
    await sharp(input)
      .resize(w, h, { fit: "cover", position: "centre" })
      .webp({ quality: q })
      .toFile(new URL(`${id}-${w}.webp`, outDir).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
  }
  done.push(id);
}
done.sort();
writeFileSync(
  new URL("src/data/clover/photos.generated.ts", root),
  `// AUTO-GENERATED by scripts/clover/photos.ts — Clover items that have a real photo in public/menu/clover/.\n` +
    `export const cloverPhotoIds: string[] = ${JSON.stringify(done, null, 2)};\n`,
);
console.log(`Photos: ${done.length} items.`);
